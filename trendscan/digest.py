"""Email digest: what is new since the last digest, as one short email.

Three steps, each testable on its own:
  1. collect_digest  — new emerging signals, trend matches, substantive new versions and new
                       editions that no earlier digest reported
  2. build_message   — an email with a plain-text and an HTML part
  3. deliver         — test mode: save it to data/digests/ (nothing is sent)
                       smtp mode: send it through the configured mail server
Entries are remembered as reported only after the digest was saved or sent.

Everything in an entry comes from public feeds or from Gemini, so it is treated as untrusted
text: HTML-escaped, and only http(s) links are kept.
"""

from __future__ import annotations

import html
import smtplib
import ssl
from dataclasses import dataclass, field
from datetime import datetime
from email.message import EmailMessage
from email.utils import formatdate, make_msgid
from pathlib import Path

from .config import Settings
from .storage import Store

SECTION_LIMIT = 15        # entries per section; the rest follow in the next digest
SECTIONS = {
    "signal": "🟣 Emerging signals",
    "match": "🟢 Matches an existing trend",
    "version": "🔁 New versions with substantive changes",
    "edition": "📚 New editions of recurring publications",
}
CONFIDENCE = {"high": 0, "medium": 1, "low": 2}
FOOTER = ("Generated by the TrendScan prototype from public sources. Summaries and assessments are "
          "AI-generated (Gemini) and the trend profiles are fictional; check the linked sources "
          "before relying on any statement.")


class DigestConfigError(Exception):
    """Sending was requested but the mail settings are incomplete."""


@dataclass
class Entry:
    key: str                                   # what is remembered as reported
    section: str                               # one of SECTIONS
    title: str
    meta: str = ""                             # publisher · date · kind
    lines: list[tuple[str, str]] = field(default_factory=list)   # (label, text)
    links: list[tuple[str, str]] = field(default_factory=list)   # (label, url)
    sort_key: tuple = ()


@dataclass
class Digest:
    entries: list[Entry]                       # listed in this digest
    held_back: dict[str, int]                  # per section: entries left for the next digest
    other_keys: list[str]                      # new items without a trend match (only counted)

    @property
    def keys(self) -> list[str]:
        return [e.key for e in self.entries] + self.other_keys

    def count(self, section: str) -> int:
        return sum(e.section == section for e in self.entries)


# ---------- 1. collect ----------

def collect_digest(store: Store, profiles: list[dict]) -> Digest:
    reported = store.reported_keys()
    names = {p["id"]: p["name"] for p in profiles}
    rows = store.inbox()
    by_id = {r["item_id"]: r for r in rows}
    candidates: list[Entry] = []
    other_keys: list[str] = []

    for r in rows:
        key = f"item:{r['item_id']}"
        a = r["analysis_result"]
        if key in reported or r["analysis_status"] != "done" or not a:
            continue                      # already reported, or not analysed yet (comes later)
        if a["emerging_signal"]["is_signal"]:
            candidates.append(_item_entry(key, "signal", r, a, names))
        elif a["trend_matches"]:
            candidates.append(_item_entry(key, "match", r, a, names))
        else:
            other_keys.append(key)

    for ch in store.done_changes():
        key = f"version:{ch['item_id']}:{ch['new_no']}"
        r = by_id.get(ch["item_id"])
        if key in reported or not r or not ch["result"]["substantive"]:
            continue
        labels = {v["version_no"]: v["label"] for v in store.get_versions(ch["item_id"])}
        res = ch["result"]
        candidates.append(Entry(
            key, "version", f"{r['title']} ({labels.get(ch['old_no'], 'old')} → {labels.get(ch['new_no'], 'new')})",
            meta=_meta(r),
            lines=[("What changed", res["summary"]), ("Revisit the assessment?", res["effect_on_assessment"])],
            links=[("Source", r["url"])], sort_key=(r["published"] or "",)))

    for link in store.get_edition_links():
        key = f"edition:{link['new_item_id']}:{link['old_item_id']}"
        new, old = by_id.get(link["new_item_id"]), by_id.get(link["old_item_id"])
        if key in reported or link["status"] != "done" or not new or not old:
            continue
        res = link["result"]
        candidates.append(Entry(
            key, "edition", new["title"], meta=_meta(new),
            lines=[("Previous edition", old["title"]), ("What changed", res["summary"]),
                   ("Technology relevance", res["technology_relevance"]),
                   ("Revisit the assessment?", res["effect_on_assessment"]),
                   ("Linked because", link["reason"])],
            links=[("New edition", new["url"]), ("Previous edition", old["url"])],
            sort_key=(new["published"] or "",)))

    entries, held_back = [], {}
    for section in SECTIONS:
        group = [e for e in candidates if e.section == section]
        if section == "match":   # strongest match first, then newest
            group.sort(key=lambda e: e.sort_key)
        else:
            group.sort(key=lambda e: e.sort_key, reverse=True)
        entries += group[:SECTION_LIMIT]
        if len(group) > SECTION_LIMIT:
            held_back[section] = len(group) - SECTION_LIMIT
    return Digest(entries, held_back, other_keys)


def _meta(r: dict) -> str:
    parts = [r["publisher"] or r["source_name"], (r["published"] or "")[:10], r["source_kind"]]
    return " · ".join(p for p in parts if p)


def _item_entry(key: str, section: str, r: dict, a: dict, names: dict) -> Entry:
    lines = [("What happened", a["what_happened"]), ("Assessment", a["assessment"])]
    if a["trend_matches"]:
        lines.append(("Trends", "; ".join(
            f"{names.get(m['profile_id'], m['profile_id'])} ({m['confidence']}): {m['explanation']}"
            for m in a["trend_matches"])))
    sig = a["emerging_signal"]
    if sig["is_signal"]:
        lines.append(("Emerging signal", f"{sig['signal_name']}: {sig['why_watch']}"))
        if sig.get("evidence_needed"):
            lines.append(("Evidence that would justify a deeper look", sig["evidence_needed"]))
    lines += [("Central-bank relevance", a["central_bank_relevance"]), ("Next step", a["next_step"]),
              ("Evidence", _evidence_note(a))]
    links = [("Source", r["url"])]
    pdf = r["doc_pdf_url"] or r["pdf_url"]
    if pdf and pdf != r["url"]:
        links.append(("PDF", pdf))
    best = min((CONFIDENCE.get(m["confidence"], 3) for m in a["trend_matches"]), default=3)
    # Matches: strongest first, then newest (negated date so one ascending sort does both).
    newest = tuple(-ord(ch) for ch in (r["published"] or ""))
    return Entry(key, section, r["title"], _meta(r), lines, links,
                 sort_key=(best, newest) if section == "match" else (r["published"] or "",))


def _evidence_note(a: dict) -> str:
    if "evidence" in a:
        ok = sum(ev["status"] in ("verified", "other_page", "spans_pages") for ev in a["evidence"])
        return f"{a['analysed_text']}; {ok} of {len(a['evidence'])} quotes verified in the PDF text"
    verified = "verified" if a.get("quote_verified") else "NOT verified"
    return f"{a['analysed_text']}; supporting quote {verified} in the source text"


# ---------- 2. build ----------

def subject_line(digest: Digest, when: datetime) -> str:
    words = {"signal": ("emerging signal", "emerging signals"), "match": ("trend match", "trend matches"),
             "version": ("new version", "new versions"), "edition": ("new edition", "new editions")}
    parts = [f"{n} {words[s][n != 1]}" for s in SECTIONS if (n := digest.count(s))]
    return f"TrendScan digest {when:%d %b %Y}: " + ", ".join(parts)


def build_message(digest: Digest, settings: Settings, when: datetime) -> EmailMessage:
    msg = EmailMessage()
    msg["Subject"] = subject_line(digest, when)
    msg["From"] = settings.email_from
    msg["To"] = ", ".join(settings.email_to) or "undisclosed-recipients:;"
    msg["Date"] = formatdate(when.timestamp(), localtime=True)
    msg["Message-ID"] = make_msgid(domain="trendscan.local")
    msg.set_content(render_text(digest, msg["Subject"]))
    msg.add_alternative(render_html(digest, msg["Subject"]), subtype="html")
    return msg


def _more(digest: Digest, section: str) -> str:
    n = digest.held_back.get(section)
    return f"… and {n} more, in the next digest (or open the app now)." if n else ""


def render_text(digest: Digest, subject: str) -> str:
    out = [subject, ""]
    for section, heading in SECTIONS.items():
        group = [e for e in digest.entries if e.section == section]
        if not group:
            continue
        out += [heading.upper(), "=" * len(heading), ""]
        for e in group:
            out += [e.title, e.meta] + [f"  {label}: {text}" for label, text in e.lines]
            out += [f"  {label}: {url}" for label, url in e.links if _safe_url(url)] + [""]
        if more := _more(digest, section):
            out += [more, ""]
    if digest.other_keys:
        out.append(f"Also collected: {len(digest.other_keys)} new items without a trend match (see the app).")
    return "\n".join(out + ["", FOOTER])


def render_html(digest: Digest, subject: str) -> str:
    e_ = html.escape
    parts = [f'<html><body style="font-family:-apple-system,Segoe UI,Arial,sans-serif;max-width:760px;'
             f'color:#1f2328;line-height:1.45"><h2 style="margin-bottom:4px">{e_(subject)}</h2>']
    for section, heading in SECTIONS.items():
        group = [e for e in digest.entries if e.section == section]
        if not group:
            continue
        parts.append(f'<h3 style="margin-top:28px;border-bottom:1px solid #d0d7de">{e_(heading)}</h3>')
        for e in group:
            link = _safe_url(e.links[0][1]) if e.links else None
            title = f'<a href="{e_(link, quote=True)}">{e_(e.title)}</a>' if link else e_(e.title)
            rows = "".join(f'<tr><td style="vertical-align:top;color:#59636e;padding:2px 12px 2px 0;'
                           f'white-space:nowrap">{e_(label)}</td><td style="padding:2px 0">{e_(text)}</td></tr>'
                           for label, text in e.lines)
            links = " · ".join(f'<a href="{e_(u, quote=True)}">{e_(label)} ↗</a>'
                               for label, url in e.links if (u := _safe_url(url)))
            parts.append(f'<div style="margin:16px 0"><div style="font-weight:600">{title}</div>'
                         f'<div style="color:#59636e;font-size:13px">{e_(e.meta)}</div>'
                         f'<table style="font-size:14px;margin-top:6px">{rows}</table>'
                         f'<div style="font-size:13px;margin-top:4px">{links}</div></div>')
        if more := _more(digest, section):
            parts.append(f"<p><em>{e_(more)}</em></p>")
    if digest.other_keys:
        parts.append(f"<p>Also collected: {len(digest.other_keys)} new items without a trend match (see the app).</p>")
    parts.append(f'<p style="color:#59636e;font-size:12px;margin-top:32px">{e_(FOOTER)}</p></body></html>')
    return "".join(parts)


def _safe_url(url: str | None) -> str | None:
    return url if url and url.lower().startswith(("https://", "http://")) else None


# ---------- 3. deliver ----------

def deliver(msg: EmailMessage, settings: Settings, when: datetime, smtp_factory=smtplib.SMTP) -> str:
    """Save (test mode) or send (smtp mode) the message. Returns where it went."""
    if settings.email_mode == "test":
        settings.digest_dir.mkdir(parents=True, exist_ok=True)
        base = settings.digest_dir / f"digest_{when:%Y-%m-%d_%H%M%S}"
        base.with_suffix(".eml").write_bytes(msg.as_bytes())     # opens in Apple Mail / Outlook
        html_part = msg.get_body(preferencelist=("html",)).get_content()
        base.with_suffix(".html").write_text(html_part, encoding="utf-8")
        return str(base.with_suffix(".html"))
    if settings.email_mode == "smtp":
        if not settings.smtp_host or not settings.email_to:
            raise DigestConfigError("TRENDSCAN_SMTP_HOST and TRENDSCAN_EMAIL_TO must be set to send email.")
        with smtp_factory(settings.smtp_host, settings.smtp_port, timeout=30) as smtp:
            smtp.starttls(context=ssl.create_default_context())   # never send credentials unencrypted
            if settings.smtp_user:
                smtp.login(settings.smtp_user, settings.smtp_password or "")
            smtp.send_message(msg)
        return ", ".join(settings.email_to)
    raise DigestConfigError(f"Unknown TRENDSCAN_EMAIL_MODE {settings.email_mode!r} (use 'test' or 'smtp').")


def run_digest(settings: Settings, store: Store, profiles: list[dict], when: datetime | None = None,
               preview: bool = False, smtp_factory=smtplib.SMTP) -> tuple[Digest, str | None]:
    """Collect, build and deliver. Returns (digest, location); location is None if nothing was new.

    preview=True writes data/digests/preview.html and remembers nothing, so the next real
    digest still contains everything."""
    when = when or datetime.now().astimezone()
    digest = collect_digest(store, profiles)
    if not digest.entries:
        return digest, None        # nothing worth an email (unmatched items are counted next time)
    msg = build_message(digest, settings, when)
    if preview:
        settings.digest_dir.mkdir(parents=True, exist_ok=True)
        path = settings.digest_dir / "preview.html"
        path.write_text(msg.get_body(preferencelist=("html",)).get_content(), encoding="utf-8")
        return digest, str(path)
    location = deliver(msg, settings, when, smtp_factory)
    store.record_digest(settings.email_mode, msg["Subject"], location, digest.keys)
    return digest, location
